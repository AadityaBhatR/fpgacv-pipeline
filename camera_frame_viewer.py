def parse_args():
    parser = argparse.ArgumentParser(description="OV5640 Live Camera Programmer & Register Control")
    parser.add_argument("--port", type=str, default=None, help="Serial port (e.g. COM3 or COM4)")
    parser.add_argument("--baud", type=int, default=921600, help="Baud rate (default: 921600)")
    parser.add_argument("--test-pattern", action="store_true", help="Enable hardware 8-color bar test pattern")
    parser.add_argument("--write-reg", nargs=2, metavar=("ADDR", "VAL"), help="Write single register, e.g. --write-reg 0x503D 0x80")
    return parser.parse_args()

def auto_detect_port():
    ports = list(serial.tools.list_ports.comports())
    if not ports:
        print("[ERROR] No COM ports found! Is your Nexys A7 Micro-USB cable connected?")
        return None
    
    print("\n--- Available COM Ports Detected on PC ---")
    selected = None
    for p in ports:
        print(f"  • {p.device}: {p.description}")
        if "Digilent" in p.description or "FTDI" in p.description or "USB Serial" in p.description:
            selected = p.device

    if selected:
        print(f"[AUTO-SELECT] Selected Nexys A7 Port: {selected}\n")
        return selected
    else:
        fallback = ports[0].device
        print(f"[AUTO-SELECT] Defaulting to port: {fallback}\n")
        return fallback

def send_camera_rom(ser, rom_table, rom_name="Custom ROM"):
    """Streams register array to FPGA over UART to program camera live on the fly."""
    count = len(rom_table)
    payload = bytearray([0x55, 0xAA, count])
    for addr_h, addr_l, data in rom_table:
        payload.extend([addr_h, addr_l, data])
    
    print(f"[CONFIG] Streaming '{rom_name}' ({count} registers, {len(payload)} bytes) at 921,600 baud...")
    ser.write(payload)
    ser.flush()
    print(f"[CONFIG] SUCCESS! Camera programmed and updated in <0.05s!\n")

def main():
    args = parse_args()
    target_port = args.port or auto_detect_port()
    
    if not target_port:
        print("[FATAL] Could not determine serial port. Exiting.")
        sys.exit(1)

    print(f"==========================================================")
    print(f"  Nexys A7 Live Camera Programmer (OV5640 RGB565 -> VGA)  ")
    print(f"  Port: {target_port} @ {args.baud} Baud                 ")
    print(f"==========================================================\n")

    try:
        ser = serial.Serial(target_port, args.baud, timeout=1.0)
    except Exception as e:
        print(f"[ERROR] Failed to open serial port {target_port}: {e}")
        sys.exit(1)

    if args.write_reg:
        addr_str, val_str = args.write_reg
        addr = int(addr_str, 16)
        val = int(val_str, 16)
        addr_h = (addr >> 8) & 0xFF
        addr_l = addr & 0xFF
        single_reg_rom = [(addr_h, addr_l, val)]
        send_camera_rom(ser, single_reg_rom, f"Single Register Write (0x{addr:04X} = 0x{val:02X})")
    elif args.test_pattern:
        print("[MODE] Enabling Hardware Color Bar Test Pattern...")
        rom = []
        for reg in QVGA_CAMERA_ROM:
            if reg[0] == 0x50 and reg[1] == 0x3D:
                rom.append((0x50, 0x3D, 0x80))
            else:
                rom.append(reg)
        send_camera_rom(ser, rom, "Hardware Color-Bar Test Pattern ROM (320x240)")
    else:
        send_camera_rom(ser, QVGA_CAMERA_ROM, "QVGA 320x240 RGB565 Baseline Live ROM")

    ser.close()
    print("[INFO] Done! Video is actively streaming to the monitor.")

if __name__ == "__main__":
    main()
